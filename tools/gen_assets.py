def jar_assets():
    tdir = os.path.join(ASSETS, "textures/block")
    os.makedirs(tdir, exist_ok=True)
    for i, (name, fn) in enumerate(JAR_TEXTURES.items()):
        tex_fill(fn, 100 + i).save(os.path.join(tdir, name + ".png"))

    for d in ("models/block", "blockstates", "items"):
        os.makedirs(os.path.join(ASSETS, d), exist_ok=True)
    loot_dir = os.path.join(ROOT, "src/main/resources/data/underworld/loot_table/blocks")
    os.makedirs(loot_dir, exist_ok=True)

    for name, (textures, elements) in JARS.items():
        tex = {k: "underworld:block/" + v for k, v in textures.items()}
        tex["particle"] = tex["glass"]
        model = {"parent": "minecraft:block/block", "ambientocclusion": False, "textures": tex, "elements": elements}
        json.dump(model, open(os.path.join(ASSETS, "models/block", name + ".json"), "w"), indent=1)
        variants = {f"facing={f}": ({"model": f"underworld:block/{name}", "y": r} if r else {"model": f"underworld:block/{name}"})
                    for f, r in (("north", 0), ("east", 90), ("south", 180), ("west", 270))}
        json.dump({"variants": variants}, open(os.path.join(ASSETS, "blockstates", name + ".json"), "w"), indent=2)
        json.dump({"model": {"type": "minecraft:model", "model": f"underworld:block/{name}"}},
                  open(os.path.join(ASSETS, "items", name + ".json"), "w"), indent=2)
        json.dump({"type": "minecraft:block", "pools": [{"rolls": 1, "conditions": [{"condition": "minecraft:survives_explosion"}],
                   "entries": [{"type": "minecraft:item", "name": f"underworld:{name}"}]}]},
                  open(os.path.join(loot_dir, name + ".json"), "w"), indent=2)

    lang_path = os.path.join(ASSETS, "lang/en_us.json")
    lang = json.load(open(lang_path)) if os.path.exists(lang_path) else {}
    for name, title in JAR_NAMES.items():
        lang[f"block.underworld.{name}"] = title
    json.dump(lang, open(lang_path, "w"), indent=2)
    print("jar assets generated")


if __name__ == "__main__":
    jar_assets()
