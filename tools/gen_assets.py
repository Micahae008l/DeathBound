def paint_cube(p, c):
    f = faces(c)
    m = c.mat
    tag = c.tag or ""

    if m == "bone":
        for name, r in f.items():
            p.fill(r, BONE)
            x0, y0, w, h = r
            # darker joint bands at both ends of long bones
            if name in ("north", "south", "east", "west") and h >= 6:
                for xx in range(w):
                    p.px(x0 + xx, y0, pick(p.rng, BONE_DARK))
                    p.px(x0 + xx, y0 + h - 1, pick(p.rng, BONE_DARK))
    elif m == "bone_dark":
        for r in f.values():
            p.fill(r, BONE_DARK)
    elif m == "ribs":
        for name, r in f.items():
            x0, y0, w, h = r
            for yy in range(h):
                for xx in range(w):
                    rib_row = yy % 2 == 0
                    sternum = name == "north" and xx in (w // 2,)
                    spine = name == "south" and xx in (w // 2,)
                    edge = name in ("up", "down") and (xx in (0, w - 1) or yy in (0, h - 1))
                    if name in ("up", "down"):
                        p.px(x0 + xx, y0 + yy, pick(p.rng, BONE) if edge else TRANSPARENT)
                    elif rib_row or sternum or spine:
                        p.px(x0 + xx, y0 + yy, pick(p.rng, BONE if rib_row else BONE_DARK))
                    else:
                        p.px(x0 + xx, y0 + yy, TRANSPARENT)
    elif m in ("cloth", "cloth_tattered"):
        for name, r in f.items():
            p.fill(r, CLOTH)
            x0, y0, w, h = r
            if m == "cloth_tattered" and name in ("north", "south", "east", "west"):
                # ragged hem: random-depth transparent notches at the bottom, a few moth holes
                for xx in range(w):
                    depth = p.rng.choice([0, 1, 1, 2, 3, 4, 5, 6]) if h > 12 else p.rng.choice([0, 1, 2])
                    for k in range(depth):
                        p.px(x0 + xx, y0 + h - 1 - k, TRANSPARENT)
                for _ in range(max(1, (w * h) // 140)):
                    hx, hy = x0 + p.rng.randrange(w), y0 + p.rng.randrange(max(1, h - 6))
                    p.px(hx, hy, TRANSPARENT)
                for yy in range(0, h, 7):  # faint fold lines
                    for xx in range(w):
                        if p.rng.random() < 0.5:
                            p.px(x0 + xx, y0 + yy, pick(p.rng, CLOTH_EDGE))
    elif m == "hood":
        for name, r in f.items():
            x0, y0, w, h = r
            if name == "north":
                # black void inside the hood, 1px cloth rim, a single eye
                for yy in range(h):
                    for xx in range(w):
                        rim = xx in (0, w - 1) or yy == 0 or (yy == 1 and xx in (1, w - 2))
                        p.px(x0 + xx, y0 + yy, pick(p.rng, CLOTH_EDGE if rim else VOID))
                ex, ey = x0 + w // 2 + 1, y0 + h // 2
                p.px(ex, ey, (150, 70, 210))
                p.gpx(ex, ey, EYE_CORE)
                # glow halo grows with the phase
                for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                    p.gpx(ex + dx, ey + dy, EYE_GLOW, phases=(2, 3), a=170)
                for dx, dy in ((-1, -1), (1, -1), (-1, 1), (1, 1), (-2, 0), (2, 0)):
                    p.gpx(ex + dx, ey + dy, EYE_GLOW, phases=(3,), a=110)
            else:
                p.fill(r, CLOTH)
                if name in ("east", "west", "south"):
                    for xx in range(w):
                        p.px(x0 + xx, y0 + h - 1, pick(p.rng, CLOTH_EDGE))
    elif m == "leather":
        for name, r in f.items():
            p.fill(r, LEATHER)
            x0, y0, w, h = r
            for yy in range(1, h, 3):  # straps / stitching
                for xx in range(w):
                    p.px(x0 + xx, y0 + yy, shade(pick(p.rng, LEATHER), 0.7))
    elif m == "metal":
        for name, r in f.items():
            p.fill(r, METAL)
            x0, y0, w, h = r
            if w > 1 and h > 1:
                p.px(x0 + 1, y0 + 1, (110, 112, 118))
    elif m == "bracer":
        for name, r in f.items():
            p.fill(r, LEATHER)
            x0, y0, w, h = r
            for xx in range(w):
                p.px(x0 + xx, y0, pick(p.rng, METAL))
                p.px(x0 + xx, y0 + h - 1, pick(p.rng, METAL))
            if h > 4 and w > 1:
                p.px(x0 + w // 2, y0 + h // 2, (104, 106, 112))
    elif m in ("wood", "wood_rune"):
        for name, r in f.items():
            p.fill(r, WOOD, vertical_streak=True)
            x0, y0, w, h = r
            for _ in range(max(1, w * h // 6)):
                p.px(x0 + p.rng.randrange(w), y0 + p.rng.randrange(h), pick(p.rng, WOOD_DARK))
            if m == "wood_rune" and name in ("north", "south", "east", "west") and h >= 3:
                ry = y0 + h // 2
                p.px(x0 + w // 2, ry, (96, 40, 140))
                p.gpx(x0 + w // 2, ry, SPECTRAL_GLOW, phases=(2, 3), a=200)
    elif m == "wood_dark":
        for r in f.values():
            p.fill(r, WOOD_DARK)
    elif m == "string":
        for r in f.values():
            p.fill(r, STRING)
    elif m == "spectral":
        for name, r in f.items():
            x0, y0, w, h = r
            for yy in range(h):
                for xx in range(w):
                    p.px(x0 + xx, y0 + yy, pick(p.rng, SPECTRAL))
                    p.gpx(x0 + xx, y0 + yy, SPECTRAL_HOT if (xx + yy) % 3 == 0 else SPECTRAL_GLOW)
    elif m == "soul":
        for name, r in f.items():
            x0, y0, w, h = r
            for yy in range(h):
                for xx in range(w):
                    p.px(x0 + xx, y0 + yy, pick(p.rng, SOUL))
                    p.gpx(x0 + xx, y0 + yy, SPECTRAL_HOT if p.rng.random() < 0.3 else SPECTRAL_GLOW, phases=(2, 3))
    # ---------------- Collector materials ----------------
    elif m in ("robe", "robe_tattered"):
        for name, r in f.items():
            p.fill(r, ROBE)
            x0, y0, w, h = r
            for _ in range(max(1, w * h // 10)):  # wear, dust, patches
                p.px(x0 + p.rng.randrange(w), y0 + p.rng.randrange(h), pick(p.rng, ROBE_DARK))
            if m == "robe_tattered" and name in ("north", "south", "east", "west"):
                for xx in range(w):
                    for k in range(p.rng.choice([0, 0, 1, 1, 2])):
                        p.px(x0 + xx, y0 + h - 1 - k, TRANSPARENT)
            if tag == "torso" and name == "north":
                for yy in range(h):  # robe opening seam
                    p.px(x0 + w // 2, y0 + yy, pick(p.rng, ROBE_DARK))
    elif m == "robe_dark":
        for r in f.values():
            p.fill(r, ROBE_DARK)
    elif m == "chood":
        for name, r in f.items():
            x0, y0, w, h = r
            if name == "north":
                for yy in range(h):
                    for xx in range(w):
                        rim = xx in (0, w - 1) or yy in (0,)
                        p.px(x0 + xx, y0 + yy, pick(p.rng, ROBE if rim else ROBE_DARK) if rim else TRANSPARENT)
            else:
                p.fill(r, ROBE)
                for _ in range(max(1, w * h // 9)):
                    p.px(x0 + p.rng.randrange(w), y0 + p.rng.randrange(h), pick(p.rng, ROBE_DARK))
    elif m == "cface":
        for name, r in f.items():
            x0, y0, w, h = r
            p.fill(r, SKIN_SHADOW)
            if name == "north":
                ey = y0 + h // 2 - 1
                for ex in (x0 + 2, x0 + w - 3):
                    p.px(ex, ey, (112, 60, 160))
                    p.gpx(ex, ey, (170, 100, 230), phases=(1,), a=150)
    elif m == "trouser":
        for name, r in f.items():
            p.fill(r, TROUSER)
            x0, y0, w, h = r
            if name in ("north", "south", "east", "west"):
                for yy in range(max(0, h - 3), h):
                    for xx in range(w):
                        p.px(x0 + xx, y0 + yy, pick(p.rng, BOOT))
    elif m == "glove":
        for r in f.values():
            p.fill(r, GLOVE)
    elif m == "belt":
        for name, r in f.items():
            p.fill(r, LEATHER)
            x0, y0, w, h = r
            if name == "north":
                p.px(x0 + w // 2, y0 + h // 2, (150, 130, 80))
                p.px(x0 + w // 2 - 1, y0 + h // 2, (150, 130, 80))
    elif m == "satchel":
        for name, r in f.items():
            p.fill(r, SATCHEL)
            x0, y0, w, h = r
            for xx in range(w):
                p.px(x0 + xx, y0, pick(p.rng, SATCHEL_TRIM))
            if name == "north" and h >= 3:
                for xx in range(w):
                    p.px(x0 + xx, y0 + 1, shade(SATCHEL[0], 0.7))
                p.px(x0 + w // 2, y0 + 2, (150, 130, 80))
    elif m == "skull":
        for name, r in f.items():
            p.fill(r, SKULL)
            x0, y0, w, h = r
            if name == "north" and w >= 2:
                p.px(x0, y0, (30, 28, 26))
                p.px(x0 + w - 1, y0, (30, 28, 26))
    elif m == "parchment":
        for name, r in f.items():
            p.fill(r, PARCHMENT)
            x0, y0, w, h = r
            if h > 1:
                p.px(x0, y0 + h // 2, (120, 40, 40))
    elif m == "key":
        for r in f.values():
            p.fill(r, KEY)
    elif m == "crystal":
        for name, r in f.items():
            x0, y0, w, h = r
            for yy in range(h):
                for xx in range(w):
                    p.px(x0 + xx, y0 + yy, (150, 90, 210))
                    p.gpx(x0 + xx, y0 + yy, (200, 140, 255), phases=(1,), a=200)
    else:
        raise SystemExit("unknown material " + m)


def render_model(root, tex_w, tex_h, out_base, glow_names, seed):
    img = Image.new("RGBA", (tex_w, tex_h), TRANSPARENT)
    glow = {p: Image.new("RGBA", (tex_w, tex_h), TRANSPARENT) for p in (1, 2, 3)}
    painter = Painter(img, glow, seed)
    for part in root.walk():
        for c in part.cubes:
            paint_cube(painter, c)
    os.makedirs(os.path.dirname(out_base), exist_ok=True)
    img.save(out_base + ".png")
    for phase, name in glow_names.items():
        glow[phase].save(os.path.join(os.path.dirname(out_base), name + ".png"))


