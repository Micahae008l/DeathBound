def faces(c):
    """Box-UV face rectangles: name -> (x, y, w, h)."""
    u, v = c.uv
    w, h, d = c.size
    return {
        "up": (u + d, v, w, d),
        "down": (u + d + w, v, w, d),
        "east": (u, v + d, d, h),
        "north": (u + d, v + d, w, h),  # model front (-Z)
        "west": (u + d + w, v + d, d, h),
        "south": (u + 2 * d + w, v + d, w, h),
    }


def shade(rgb, f):
    return tuple(max(0, min(255, int(round(ch * f)))) for ch in rgb)


def pick(rng, palette):
    return palette[rng.randrange(len(palette))]


TRANSPARENT = (0, 0, 0, 0)


class Painter:
    def __init__(self, img, glow, seed):
        self.img = img
        self.glow = glow  # dict phase -> Image (emissive layers) or None
        self.rng = random.Random(seed)

    def px(self, x, y, rgb, a=255):
        if 0 <= x < self.img.width and 0 <= y < self.img.height:
            self.img.putpixel((x, y), (*rgb, a) if len(rgb) == 3 else rgb)

    def gpx(self, x, y, rgb, phases=(1, 2, 3), a=255):
        if self.glow is None:
            return
        for p in phases:
            g = self.glow[p]
            if 0 <= x < g.width and 0 <= y < g.height:
                g.putpixel((x, y), (*rgb, a))

    def fill(self, rect, palette, face=None, vertical_streak=False):
        x0, y0, w, h = rect
        for yy in range(h):
            for xx in range(w):
                col = pick(self.rng, palette)
                if vertical_streak and (xx % 3 == 0):
                    col = shade(col, 0.82)
                self.px(x0 + xx, y0 + yy, col)


