def bow_pulling(base_rows, pull):
    """Pull the string back (to the right) by shifting string pixels."""
    rows = [list(r) for r in base_rows]
    for y in range(16):
        for x in range(16):
            if rows[y][x] == "s":
                rows[y][x] = "."
    # string from top tip (13,0)->(3,13) bent toward the nock point
    top, bottom = (12, 1), (2, 14)
    mid = (7 + pull, 7 + pull)
    for (a, b) in ((top, mid), (mid, bottom)):
        steps = max(abs(b[0] - a[0]), abs(b[1] - a[1]))
        for i in range(steps + 1):
            x = round(a[0] + (b[0] - a[0]) * i / steps)
            y = round(a[1] + (b[1] - a[1]) * i / steps)
            if rows[y][x] == ".":
                rows[y][x] = "s"
    # nocked hollow arrow pointing toward the upper right
    ax, ay = mid
    for i in range(1, 6 + pull):
        x, y = ax - i, ay - i
        if 0 <= x < 16 and 0 <= y < 16 and rows[y][x] in ".s":
            rows[y][x] = "d"
    hx, hy = ax - 6 - pull, ay - 6 - pull
    for dx, dy, ch in ((0, 0, "P"), (-1, 0, "p"), (0, -1, "p"), (-1, -1, "a")):
        x, y = hx + dx, hy + dy
        if 0 <= x < 16 and 0 <= y < 16:
            rows[y][x] = ch
    return ["".join(r) for r in rows]


