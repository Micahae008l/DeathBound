"""
Single source of truth for the Underworld character models + textures.

Each model is a tree of parts made of boxes (Minecraft "box UV" layout). This script:
  1. packs every box into a texture atlas,
  2. writes the Java LayerDefinition (src/client/java/.../geom/*Geometry.java),
  3. paints the pixel textures (base + emissive "eyes" layers),
  4. paints the item / effect icons.

Re-run after editing:  python3 tools/gen_assets.py
"""
